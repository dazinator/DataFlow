    #region DI Scoping Tests

    [Fact]
    public async Task Should_MaintainSeparateDIScopes_ForEachBranch()
    {
        // Arrange - Verify that each branch gets its own DI scope
        var services = new ServiceCollection();
        AddDefaultServices(services);

        // Register a scoped service to track scope instances
        var scopeInstances = new ConcurrentBag<int>();
        services.AddScoped<ScopedTestService>(sp => new ScopedTestService(scopeInstances));

        var sp = services.BuildServiceProvider();
        var builder = new StructuredDataFlowBuilder(sp, "ScopedTest");

        var items = Enumerable.Range(1, 10).ToArray();
        builder.AddProducer<int>("source", (IServiceProvider sp) => new TestProducer<int>(items));

        builder.AddBroadcast<int>("fanout")
            .ReceiveFrom("source");

        // Create 3 concurrent branches
        for (var i = 0; i < 3; i++)
        {
            var branchBuilder = builder.AddBranch($"branch-{i}");
            var processorBuilder = StructuredDataFlowBuilderExtensions.AddProcessor<int>(branchBuilder, $"processor-{i}",
                (IServiceProvider sp) => new ScopedProcessor(sp.GetRequiredService<ScopedTestService>()));
            processorBuilder.ReceiveFrom("fanout");
        }

        var flow = await builder.Build();

        // Act
        var context = CreateContext("test", Guid.NewGuid(), sp);
        await flow.ExecuteAsync(context);

        // Assert - Should have multiple scope instances (one per branch actor)
        scopeInstances.Count.ShouldBe(3);
        _output.WriteLine($"Total scope instances created: {scopeInstances.Count}");
    }

    private class ScopedTestService
    {
        private readonly ConcurrentBag<int> _scopeInstances;

        public ScopedTestService(ConcurrentBag<int> scopeInstances)
        {
            _scopeInstances = scopeInstances;
            InstanceId = scopeInstances.Count + 1;
            _scopeInstances.Add(InstanceId);
        }

        public int InstanceId { get; }
    }

    private class ScopedProcessor : IStreamProcessor<int>
    {
        private readonly ScopedTestService _scopedService;

        public ScopedProcessor(ScopedTestService scopedService)
        {
            _scopedService = scopedService;
        }

        public async Task ProcessAsync(
            IDataFlowContext context,
            IAsyncEnumerable<int> input,
            CancellationToken cancellationToken)
        {
            await foreach (var item in input.WithCancellation(cancellationToken))
            {
                // Just consume the items
                await Task.Yield();
            }
        }
    }

    #endregion
